fun stringsFor(lang: Language): AppStrings = if (lang == Language.BN) BnStrings else EnStrings

fun matchModeLabel(lang: Language, mode: MatchMode): String = when (mode) {
    MatchMode.EXACT -> if (lang == Language.BN) "হুবহু মিল (Exact)" else "Exact Match"
    MatchMode.LIST -> if (lang == Language.BN) "একাধিক তালিকা (List)" else "Comma List"
    MatchMode.CONTAINS -> if (lang == Language.BN) "অংশবিশেষ (Contains)" else "Contains"
    MatchMode.STARTS_WITH -> if (lang == Language.BN) "শুরু হয় (Starts With)" else "Starts With"
    MatchMode.REGEX -> if (lang == Language.BN) "রেগুলার এক্সপ্রেশন (Regex)" else "Regex"
}

fun logStatusLabel(lang: Language, status: LogStatus): String = when (status) {
    LogStatus.FORWARDED -> if (lang == Language.BN) "ফরওয়ার্ড হয়েছে" else "Forwarded"
    LogStatus.IGNORED -> if (lang == Language.BN) "বাদ" else "Ignored"
    LogStatus.FAILED -> if (lang == Language.BN) "ব্যর্থ" else "Failed"
    LogStatus.DRY_RUN -> if (lang == Language.BN) "ড্রাই-রান" else "Dry Run"
}
